#!/usr/bin/env bash
set -euo pipefail
AIKIT="$(cd "$(dirname "$0")/../../.." && pwd)"
# shellcheck source=../lib/harness.sh
source "$AIKIT/tests/bin/lib/harness.sh"

echo "=== default_mode semantics parity (#144) ==="
# section: default_mode semantics
# `default_mode: always-on` is enforcement on both hosts: Cursor via
# alwaysApply: true, Claude Code via the host's native loader, which reads
# every pathless .claude/rules/*.md at session start and a file with `paths:`
# only on touch (#182, measured 2026-09-19). on-demand therefore emits a glob
# nothing matches. This test pins that behaviour so a future edit can't
# silently change what a mode value does on either host, or add an emitter
# whose emit_<agent>() accepts $mode and never looks at it.

TMP=$(mktemp -d)

"$AIKIT/bin/emit-rules.sh" "$TMP" --rules git-hygiene --agents cursor --mode always-on >/dev/null
cp "$TMP/.cursor/rules/git-hygiene.mdc" "$TMP/cursor-always.mdc"
"$AIKIT/bin/emit-rules.sh" "$TMP" --rules git-hygiene --agents cursor --mode on-demand >/dev/null
cp "$TMP/.cursor/rules/git-hygiene.mdc" "$TMP/cursor-on-demand.mdc"

assert "cursor: always-on sets alwaysApply: true" \
  'grep -q "^alwaysApply: true$" "$TMP/cursor-always.mdc"'
assert "cursor: on-demand sets alwaysApply: false" \
  'grep -q "^alwaysApply: false$" "$TMP/cursor-on-demand.mdc"'

"$AIKIT/bin/emit-rules.sh" "$TMP" --rules git-hygiene --agents claude-code --mode always-on >/dev/null
cp "$TMP/.claude/rules/git-hygiene.md" "$TMP/claude-always.md"
"$AIKIT/bin/emit-rules.sh" "$TMP" --rules git-hygiene --agents claude-code --mode on-demand >/dev/null
cp "$TMP/.claude/rules/git-hygiene.md" "$TMP/claude-on-demand.md"

assert "claude-code: always-on recorded in header comment" \
  'grep -q "Mode: always-on" "$TMP/claude-always.md"'
assert "claude-code: on-demand recorded in header comment" \
  'grep -q "Mode: on-demand" "$TMP/claude-on-demand.md"'
# On Claude Code the mode is structural: always-on stays pathless (native
# loader picks it up every session), on-demand is fenced behind a glob
# nothing matches. A rule that declares its own `paths:` keeps them.
assert "claude-code: always-on emits no frontmatter (loaded every session)" \
  'head -1 "$TMP/claude-always.md" | grep -q "^<!-- Generated by ai-kit"'
assert "claude-code: on-demand is fenced behind a never-matching glob (#182)" \
  'head -2 "$TMP/claude-on-demand.md" | grep -q "^paths: \[\".on-demand/\*\*\"\]$"'
"$AIKIT/bin/emit-rules.sh" "$TMP" --rules laravel-conventions --agents claude-code >/dev/null
assert "claude-code: a rule's own paths: is passed through" \
  'head -2 "$TMP/.claude/rules/laravel-conventions.md" | grep -q "^paths: \[\"app/\*\*\""'

# A new emitter that declares $mode as its 4th argument (per the contract in
# emitters/README.md) but never reads it would repeat the Claude Code gap
# silently. Every emitter file must reference $mode somewhere in its body.
for f in "$AIKIT"/bin/lib/emitters/*.sh; do
  agent="$(basename "$f" .sh)"
  assert "emitter '$agent' reads \$mode" 'grep -qE "\\\$\{?mode\}?" "$f"'
done

# Source invariants the emitter relies on: paths: is a single-line flow list
# (block YAML returns empty from _emitter_extract_meta and silently drops the
# scope), and an on-demand rule never carries paths: (its scope is the
# sentinel; a skill reads it by path).
assert "rules: every paths: is a single-line flow list" \
  '! grep -rhE "^paths:" "$AIKIT/standards/rules" --include="*.mini.md" | grep -vqE "^paths: \[.*\]$"'
assert "rules: no on-demand rule declares paths:" \
  '! grep -lE "^paths:" -r "$AIKIT/standards/rules" --include="*.mini.md" | xargs grep -l "^default_mode: on-demand" | grep -q .'

rm -rf "$TMP"

print_summary_and_exit
