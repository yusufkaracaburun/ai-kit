#!/usr/bin/env bash
set -euo pipefail
AIKIT="$(cd "$(dirname "$0")/../../.." && pwd)"
# shellcheck source=../lib/harness.sh
source "$AIKIT/tests/bin/lib/harness.sh"

# #322: once ~/.claude/rules/ai-kit serves the universal rules, /ai:upgrade
# deletes a project copy only when it matches a released version of that rule.
# A throwaway kit holds the rules and the checksum list, so a rule edited after
# the list was built stands in for "the copy is an older release".

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
KIT="$T/kit" H="$T/home" BARE="$T/bare"
mkdir -p "$KIT/standards" "$H/.claude/rules" "$BARE" "$T/served"
ln -s "$AIKIT/bin" "$KIT/bin"
cp "$AIKIT/VERSION" "$KIT/VERSION"
cp -R "$AIKIT/standards/rules" "$KIT/standards/rules"
kitgit() { git -C "$KIT" -c user.email=t@t -c user.name=t "$@"; }
kitgit init --quiet && kitgit add standards && kitgit commit --quiet -m rules && kitgit tag v0.0.1
python3 "$AIKIT/bin/lib/rule-checksums.py" build "$KIT"
TPL="$T/template"
mkdir -p "$TPL"
printf '{\n  "ai_kit_version": "0.0.1",\n  "branches": {}\n}\n' > "$TPL/.ai-kit-setup"
AI_KIT_ROOT="$KIT" bash "$AIKIT/bin/emit-rules.sh" "$TPL" --set universal --agents claude-code --no-index >/dev/null
AI_KIT_ROOT="$KIT" bash "$AIKIT/bin/emit-rules.sh" "$TPL" --rules a11y --agents claude-code --no-index >/dev/null
echo "- a line a newer release added" >> "$KIT/standards/rules/git-hygiene.mini.md"
touch "$T/served/git-hygiene.md" "$T/served/writing-style.md" "$T/served/quality-floor.md"
ln -s "$T/served" "$H/.claude/rules/ai-kit"

make_project() {
  local p="$1"
  cp -R "$TPL" "$p"
  # Header as the first releases wrote it, before the stamp and description changes.
  sed -i.bak -e '/^<!-- Generated by ai-kit/c\
<!-- Generated by ai-kit @ 1.0.0 from standards/rules/git-hygiene.mini.md -->' \
    -e '/^<!-- Mode:/c\
<!-- Mode: always-on. Re-emit with: bin/emit-rules.sh <project> --update -->' \
    "$p/.claude/rules/git-hygiene.md" && rm "$p/.claude/rules/git-hygiene.md.bak"
  echo "- my own house rule" >> "$p/.claude/rules/writing-style.md"
  echo "# hand-written" > "$p/.claude/rules/team.md"
}

upgrade() { HOME="$1" AI_KIT_ROOT="$KIT" bash "$AIKIT/bin/ai-kit-upgrade.sh" "$2" 2>&1; }

echo "=== served: released copy removed, edited copy kept and listed ==="
# section: upgrade-removes-released-rule-copies
P="$T/p"
make_project "$P"
EDITED="$(cat "$P/.claude/rules/writing-style.md")"
OUT="$(upgrade "$H" "$P")"
assert "copy matching a released version removed" '[ ! -e "$P/.claude/rules/git-hygiene.md" ]'
assert "hand-edited copy kept" '[ -f "$P/.claude/rules/writing-style.md" ]'
assert "hand-edited copy not re-emitted" '[ "$EDITED" = "$(cat "$P/.claude/rules/writing-style.md")" ]'
assert "hand-edited copy listed in the output" 'echo "$OUT" | grep -q "\.claude/rules/writing-style\.md"'
assert "unedited copy of a current rule removed" '[ ! -e "$P/.claude/rules/quality-floor.md" ]'
assert "removal named in the output" 'echo "$OUT" | grep -q "removed: \.claude/rules/git-hygiene\.md"'
assert "stack rule untouched" '[ -f "$P/.claude/rules/a11y.md" ]'
assert "hand-written rule untouched" '[ "$(cat "$P/.claude/rules/team.md")" = "# hand-written" ]'

echo "=== edits the emitter never makes: copy kept ==="
# section: upgrade-rule-copies-edited-kept
P="$T/p-repoint"
make_project "$P"
sed -i.bak 's|](\./pre-write-discipline\.md)|](./writing-style.md)|' "$P/.claude/rules/quality-floor.md"
assert "fixture repointed the link" 'grep -q "](./writing-style.md)" "$P/.claude/rules/quality-floor.md"'
upgrade "$H" "$P" >/dev/null
assert "copy with a repointed rule link kept" '[ -f "$P/.claude/rules/quality-floor.md" ]'
P="$T/p-comment"
make_project "$P"
perl -0pi -e 's/\n\n/\n<!-- Team: reviewed by platform -->\n\n/' "$P/.claude/rules/git-hygiene.md"
upgrade "$H" "$P" >/dev/null
assert "copy with a leading team comment kept" '[ -f "$P/.claude/rules/git-hygiene.md" ]'

echo "=== opt-out set: nothing removed ==="
# section: upgrade-rule-copies-opt-out
P="$T/p-optout"
make_project "$P"
mkdir -p "$H/.config/ai-kit" && touch "$H/.config/ai-kit/no-global-rules"
upgrade "$H" "$P" >/dev/null
rm "$H/.config/ai-kit/no-global-rules"
assert "opt-out keeps the released copy" '[ -f "$P/.claude/rules/git-hygiene.md" ]'

echo "=== no rules link: nothing removed ==="
# section: upgrade-rule-copies-no-link
P="$T/p-nolink"
make_project "$P"
upgrade "$BARE" "$P" >/dev/null
assert "no link keeps the released copy" '[ -f "$P/.claude/rules/git-hygiene.md" ]'

echo "=== an unedited copy is in the list ==="
# section: rule-checksum-matches-emitter-output
WS="$TPL/.claude/rules/writing-style.md"
assert "emitted copy hashes to a listed version" \
  'grep -qxF "writing-style $(python3 "$AIKIT/bin/lib/rule-checksums.py" hash "$WS")" "$KIT/standards/rule-checksums.txt"'
assert "list holds the rules as built" 'grep -q "^writing-style [0-9a-f]\{64\}$" "$KIT/standards/rule-checksums.txt"'
assert "list skips stack rules" '! grep -q "^a11y " "$KIT/standards/rule-checksums.txt"'

echo "=== build fails loud ==="
# section: rule-checksums-build-fails-loud
NOTAGS="$T/notags"
mkdir -p "$NOTAGS/standards" && cp -R "$AIKIT/standards/rules" "$NOTAGS/standards/rules"
assert "build without v* tags exits non-zero" '! python3 "$AIKIT/bin/lib/rule-checksums.py" build "$NOTAGS" 2>/dev/null'
assert "build without v* tags writes no list" '[ ! -e "$NOTAGS/standards/rule-checksums.txt" ]'
seq 1 5000 > "$KIT/standards/rule-checksums.txt"
assert "build that would shrink the list exits non-zero" '! python3 "$AIKIT/bin/lib/rule-checksums.py" build "$KIT" 2>/dev/null'
assert "shrinking build leaves the list as it was" '[ "$(wc -l < "$KIT/standards/rule-checksums.txt")" -eq 5000 ]'

print_summary_and_exit
