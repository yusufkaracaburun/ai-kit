# shellcheck shell=bash
# Claude Code rule emitter — Claude Code has no "rules" primitive, so we
# emit to .claude/rules/<name>.md (read by agent on demand) and append a
# pointer to docs/agents/active-rules.md.

emit_claude_code() {
  local target="$1" rule_path="$2" rule_name="$3" mode="$4" aikit_version="$5"
  local dest="$target/.claude/rules/${rule_name}.md"

  mkdir -p "$(dirname "$dest")"
  {
    echo "<!-- Generated by ai-kit @ ${aikit_version} from standards/rules/${rule_name}.mini.md -->"
    echo "<!-- Mode: ${mode}. Re-emit with: bin/emit-rules.sh <project> --update -->"
    echo ""
    _emitter_strip_frontmatter "$rule_path"
  } > "$dest"
  echo "emit:claude-code  ${dest#$target/}"
}
