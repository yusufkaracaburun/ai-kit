# shellcheck shell=bash
# Aider rule emitter — writes .aider/rules/<name>.md. Aider has no rules-dir
# auto-discovery, so the emitted file's header tells the user to add it to the
# `read:` list in .aider.conf.yml (Aider's always-on context mechanism).

emit_aider() {
  local target="$1" rule_path="$2" rule_name="$3" mode="$4" aikit_version="$5"
  local dest="$target/.aider/rules/${rule_name}.md"

  mkdir -p "$(dirname "$dest")"
  {
    echo "<!-- Generated by ai-kit @ ${aikit_version} from standards/rules/${rule_name}.mini.md -->"
    echo "<!-- Mode: ${mode}. Add '.aider/rules/${rule_name}.md' to the read: list in .aider.conf.yml -->"
    echo "<!-- Re-emit with: bin/emit-rules.sh <project> --update -->"
    echo ""
    _emitter_strip_frontmatter "$rule_path"
  } > "$dest"
  echo "emit:aider  ${dest#$target/}"
}
