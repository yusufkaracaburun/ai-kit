# shellcheck shell=bash
# Cursor rule emitter — writes .cursor/rules/<name>.mdc with frontmatter.

emit_cursor() {
  local target="$1" rule_path="$2" rule_name="$3" mode="$4" aikit_version="$5"
  local dest="$target/.cursor/rules/${rule_name}.mdc"
  local always="false"
  [ "$mode" = "always-on" ] && always="true"

  local description
  description="$(_emitter_extract_meta "$rule_path" description)"
  [ -z "$description" ] && description="${rule_name} (ai-kit canonical rule)"

  mkdir -p "$(dirname "$dest")"
  {
    echo "---"
    echo "description: ${description}"
    echo "globs:"
    echo "alwaysApply: ${always}"
    echo "---"
    echo ""
    echo "<!-- Generated by ai-kit @ ${aikit_version} from standards/rules/${rule_name}.mini.md -->"
    echo "<!-- Re-emit with: bin/emit-rules.sh <project> --update -->"
    echo ""
    _emitter_strip_frontmatter "$rule_path"
  } > "$dest"
  echo "emit:cursor  ${dest#$target/}"
}
