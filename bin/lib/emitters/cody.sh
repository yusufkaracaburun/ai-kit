# shellcheck shell=bash
# Cody rule emitter — writes .sourcegraph/cody/<name>.md. Cody's context
# fetcher picks up Markdown files under .sourcegraph/cody/.

emit_cody() {
  local target="$1" rule_path="$2" rule_name="$3" mode="$4" aikit_version="$5"
  local dest="$target/.sourcegraph/cody/${rule_name}.md"

  mkdir -p "$(dirname "$dest")"
  {
    echo "<!-- Generated by ai-kit @ ${aikit_version} from standards/rules/${rule_name}.mini.md -->"
    echo "<!-- Mode: ${mode}. Read by Cody's context fetcher from .sourcegraph/cody/. Re-emit: bin/emit-rules.sh <project> -->"
    echo ""
    _emitter_strip_frontmatter "$rule_path"
  } > "$dest"
  echo "emit:cody  ${dest#$target/}"
}
