# shellcheck shell=bash
# Cline rule emitter — writes .clinerules/<name>.md. Cline auto-loads every
# Markdown file in the .clinerules/ directory. A legacy single-file
# .clinerules cannot also be a directory, so that case is skipped (with a
# reason) rather than clobbered.

emit_cline() {
  local target="$1" rule_path="$2" rule_name="$3" mode="$4" aikit_version="$5"

  if [ -f "$target/.clinerules" ]; then
    echo "skip:cline  ${rule_name} (.clinerules is a legacy single file — migrate it to a .clinerules/ directory to receive per-rule emits)"
    return 0
  fi

  local dest="$target/.clinerules/${rule_name}.md"
  mkdir -p "$(dirname "$dest")"
  {
    echo "<!-- Generated by ai-kit @ ${aikit_version} from standards/rules/${rule_name}.mini.md -->"
    echo "<!-- Mode: ${mode}. Auto-loaded by Cline from .clinerules/. Re-emit: bin/emit-rules.sh <project> -->"
    echo ""
    _emitter_strip_frontmatter "$rule_path"
  } > "$dest"
  echo "emit:cline  ${dest#$target/}"
}
