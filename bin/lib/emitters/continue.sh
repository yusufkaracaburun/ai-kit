# shellcheck shell=bash
# Continue rule emitter — writes .continue/rules/<name>.md. Continue auto-loads
# every Markdown rule file under .continue/rules/ as tagged context.

emit_continue() {
  local target="$1" rule_path="$2" rule_name="$3" mode="$4" aikit_version="$5"
  local dest="$target/.continue/rules/${rule_name}.md"

  mkdir -p "$(dirname "$dest")"
  {
    echo "<!-- Generated by ai-kit @ ${aikit_version} from standards/rules/${rule_name}.mini.md -->"
    echo "<!-- Mode: ${mode}. Auto-loaded by Continue from .continue/rules/. Re-emit: bin/emit-rules.sh <project> -->"
    echo ""
    _emitter_strip_frontmatter "$rule_path"
  } > "$dest"
  echo "emit:continue  ${dest#$target/}"
}
