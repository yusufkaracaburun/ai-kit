# shellcheck shell=bash
# Claude Code rule emitter — writes .claude/rules/<name>.md. Claude Code
# loads every file in that directory that has no `paths:` frontmatter at
# session start, and a file with `paths:` only when a matching file is
# touched (measured 2026-09-19, CC 2.1.278 — #182). So:
#   - a rule whose source declares `paths:` is emitted with it (on touch)
#   - an on-demand rule without `paths:` gets a glob nothing matches — it
#     is never auto-loaded; skills that need it read it by path
#   - an always-on rule without `paths:` stays pathless — loaded every session
# Also appends a pointer to docs/agents/active-rules.md.

emit_claude_code() {
  local target="$1" rule_path="$2" rule_name="$3" mode="$4" aikit_version="$5"
  local dest="$target/.claude/rules/${rule_name}.md"
  local paths
  paths="$(_emitter_extract_meta "$rule_path" paths)"
  [ -z "$paths" ] && [ "$mode" = "on-demand" ] && paths='[".on-demand/**"]'

  mkdir -p "$(dirname "$dest")"
  {
    if [ -n "$paths" ]; then
      echo "---"
      echo "paths: ${paths}"
      echo "---"
    fi
    echo "<!-- Generated by ai-kit @ ${aikit_version} from standards/rules/${rule_name}.mini.md -->"
    echo "<!-- Mode: ${mode}. Re-emit with: bin/emit-rules.sh <project> -->"
    echo ""
    _emitter_body "$rule_path" md
  } > "$dest"
  echo "emit:claude-code  ${dest#$target/}"
}
