#!/usr/bin/env python3
"""Checksums of every released universal rule, so /ai:upgrade can tell an
unmodified per-repo copy from a hand-edited one (ADR-0015, #322).

  rule-checksums.py hash <file>       checksum of an emitted copy
  rule-checksums.py build <kit-root>  rewrite <kit-root>/standards/rule-checksums.txt
                                      from the rules at every v* tag plus the tree

A copy is hashed as written, minus its frontmatter and the emitter's own
header lines. The build hashes what the emitter wrote: the raw body (before
link rewriting existed) and the rewritten body for each emitted set that
changes a link. Universal rules were always emitted together, so only links
to stack rules vary.
"""
import hashlib
import itertools
import re
import subprocess
import sys
from pathlib import Path

FENCE = re.compile(r"---\s*")
EMITTER_HEADER = ("<!-- Generated by ai-kit", "<!-- Mode:", "<!-- Source:", "<!-- ai-kit")
LINK = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)]+)\)")
EXTERNAL = re.compile(r"(?:https?:|mailto:|tel:|//|#)")
RULE_PATH = re.compile(r"(?:^|/)standards/rules/(?:feedback/)?([^/]+)\.(?:mini|nano)\.md$")
UNIVERSAL = re.compile(r"^universal:\s*true\s*$", re.M)
MAX_VARIANT_LINKS = 6


def split_frontmatter(text):
    lines = text.split("\n")
    if FENCE.fullmatch(lines[0]):
        for i in range(1, len(lines)):
            if FENCE.fullmatch(lines[i]):
                return "\n".join(lines[1:i]), "\n".join(lines[i + 1:])
    return "", text


def checksum(text):
    lines = split_frontmatter(text)[1].split("\n")
    while lines and (not lines[0].strip() or lines[0].startswith(EMITTER_HEADER)):
        lines.pop(0)
    return hashlib.sha256(("\n".join(lines).rstrip() + "\n").encode()).hexdigest()


def link_rule(target):
    target = re.sub(r"#.*$", "", target)
    cand = re.sub(r".*/", "", target)
    for suffix in (r"\.(?:mini|nano)\.md$", r"\.md$", r"\.(?:mini|nano)$"):
        cand = re.sub(suffix, "", cand)
    return cand


# Port of _emitter_body's link rewrite in emitter-lib.sh; keep the two in step.
def rewrite_links(body, emitted):
    def one(m):
        label, target = m.group(1), m.group(2)
        if EXTERNAL.match(target):
            return m.group(0)
        anchor = re.search(r"#.*$", target)
        cand = link_rule(target)
        if not cand or cand not in emitted:
            return label
        label = re.sub(r"^(`?)" + re.escape(cand) + r"(?:\.(?:mini|nano))?\.md(`?)$", r"\1" + cand + r"\2", label)
        return f"[{label}](./{cand}.md{anchor.group(0) if anchor else ''})"
    return LINK.sub(one, body)


def emitted_variants(body, universal, stack):
    yield body
    linked = sorted({link_rule(m.group(2)) for m in LINK.finditer(body)} & stack)[:MAX_VARIANT_LINKS]
    for n in range(len(linked) + 1):
        for extra in itertools.combinations(linked, n):
            yield rewrite_links(body, universal | set(extra))


def git(root, *args, stdin=None):
    return subprocess.run(["git", "-C", str(root), *args], input=stdin,
                          capture_output=True, check=False).stdout


def tagged_releases(root, tags):
    for tag in tags:
        specs = []
        paths = git(root, "ls-tree", "-r", "--name-only", tag, "--",
                    "standards/rules", "workflow/standards/rules").decode().split("\n")
        for p in paths:
            m = RULE_PATH.search(p)
            if m:
                specs.append((m.group(1), f"{tag}:{p}"))
        if not specs:
            continue
        out = git(root, "cat-file", "--batch", stdin="\n".join(s for _, s in specs).encode() + b"\n")
        rules, pos = {}, 0
        for name, _ in specs:
            end = out.index(b"\n", pos)
            size = int(out[pos:end].split()[2])
            rules[name] = out[end + 1:end + 1 + size].decode()
            pos = end + 1 + size + 1
        yield rules


def tree_release(root):
    rules = {}
    for path in sorted((root / "standards" / "rules").glob("**/*.md")):
        m = RULE_PATH.search(path.as_posix())
        if m:
            rules[m.group(1)] = path.read_text()
    return rules


def build(root):
    root = Path(root)
    out_file = root / "standards" / "rule-checksums.txt"
    tags = git(root, "tag", "--list", "v*").decode().split()
    if not tags:
        sys.exit(f"rule-checksums: no v* tags in {root}; a list without released versions would keep every copy")
    entries = set()
    for rules in [*tagged_releases(root, tags), tree_release(root)]:
        fronts = {name: split_frontmatter(text) for name, text in rules.items()}
        universal = {name for name, (fm, _) in fronts.items() if UNIVERSAL.search(fm)}
        stack = set(fronts) - universal
        for name in universal:
            for body in emitted_variants(fronts[name][1], universal, stack):
                entries.add(f"{name} {checksum(body)}")
    old = len(out_file.read_text().splitlines()) if out_file.exists() else 0
    if len(entries) < old:
        sys.exit(f"rule-checksums: new list has {len(entries)} lines, {out_file} has {old}; a release never drops a version")
    out_file.write_text("".join(f"{e}\n" for e in sorted(entries)))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "hash":
        print(checksum(Path(sys.argv[2]).read_text()))
    elif len(sys.argv) == 3 and sys.argv[1] == "build":
        build(sys.argv[2])
    else:
        sys.exit(__doc__)
